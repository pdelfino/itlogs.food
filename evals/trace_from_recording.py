"""Turn recorded sessions into the files replay.py and the README's numbers come from.

uv run --project server python evals/trace_from_recording.py <recordings folder>

Writes evals/traces/<session>.json for the sessions named in CHOSEN and evals/recorded-runs.org
for every session. What leaves a recording: the food name, grams, confidence and raw value of each
read, whether the scene was still, read latency, and the rows logged. Never photos, never speech.
The recordings themselves stay out of git.
"""

from __future__ import annotations

import bisect
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OPEN_WEIGHT = {
    "2026-11-03-194511"
}  # read with Muse Spark Open on Baseten; every other is Muse Spark

CHOSEN = {
    "2026-11-03-201500": "The best run: apple, then banana, no zero between them.",
    "2026-11-02-195113": "One apple and one banana logged as five rows, before a re-read of the "
    "same food corrected its row.",
    "2026-11-02-195734": "One banana logged twice around a single 0 g read, a hand over the display.",
    "2026-11-02-194354": "One banana logged as banana and whole banana.",
    "2026-11-03-214319": "One bar logged as protein bar and granola bar at the same grams.",
    "2026-11-03-215802": "The worst failure, a dim kitchen: the reader named a food on nearly "
    "every frame and read one weight. Nothing logged. Software did not fix this.",
    "2026-11-04-080057": "A bowl built from four ingredients. Logged as 265 g in four rows; the "
    "scale showed about 104 g across one tare. The reader had no vessel field yet, so this replay "
    "assumes the bowl. Names here are the reader's: naming an ingredient takes a model call.",
}
ASSUME_VESSEL = {"2026-11-04-080057"}


def load(folder: Path) -> dict | None:
    path = folder / "session.json"
    if not path.exists():
        return None
    events = json.loads(path.read_text()).get("events", [])
    motion = [(e["t_ms"], e["still"]) for e in events if e["kind"] == "motion"]
    times = [t for t, _ in motion]
    reads = []
    for e in events:
        if e["kind"] != "read":
            continue
        i = bisect.bisect_right(times, e["t_ms"]) - 1
        reads.append(
            {
                "t_ms": e["t_ms"],
                "food": e.get("food", "none"),
                "grams": e.get("grams"),
                "confidence": e.get("confidence", 0.0),
                "raw": e.get("raw"),
                "still": motion[i][1] if i >= 0 else True,
            }
        )
    rows: dict[int, dict] = {}
    for e in events:
        if e["kind"] == "entry" and e.get("entry"):
            rows[e["entry"]["index"]] = e["entry"]
    return {
        "reads": reads,
        "read_ms": [e["ms"] for e in events if e["kind"] == "read_latency"],
        "logged_then": [[r["food"], r["grams"]] for _, r in sorted(rows.items())],
    }


def main() -> int:
    root = Path(sys.argv[1])
    out = [
        "#+TITLE: Every recorded session",
        "",
        (
            "Generated by =trace_from_recording.py= from the recordings of real runs: Ray-Ban Meta "
            "glasses, a real scale, a real model. Rows are what the app logged at the time, under "
            "the code of that moment."
        ),
        "",
        "| Session | Reader | Reads | With a weight | Median read | Rows logged |",
        "|---------+--------+-------+---------------+-------------+-------------|",
    ]
    spark: list[int] = []
    reads_total = weighed_total = runs_with_reads = runs = 0
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        run = load(folder)
        if run is None:
            continue
        runs += 1
        name = folder.name
        reads, ms = run["reads"], run["read_ms"]
        weighed = sum(1 for r in reads if r["grams"] is not None and r["grams"] > 0)
        reads_total += len(reads)
        weighed_total += weighed
        runs_with_reads += bool(reads)
        if name not in OPEN_WEIGHT:
            spark += ms
        median = f"{statistics.median(ms) / 1000:.1f} s" if ms else "-"
        logged = ", ".join(f"{f} {g:g} g" for f, g in run["logged_then"]) or "-"
        reader = "Muse Spark Open" if name in OPEN_WEIGHT else "Muse Spark"
        out.append(
            f"| {name} | {reader} | {len(reads)} | {weighed} | {median} | {logged} |"
        )
        if name in CHOSEN:
            trace = {
                "session": name,
                "why": CHOSEN[name],
                "assume_vessel": name in ASSUME_VESSEL,
                **run,
            }
            path = HERE / "traces" / f"{name}.json"
            path.write_text(json.dumps(trace, indent=1) + "\n")
    spark.sort()
    out += [
        "",
        (
            f"{runs} sessions, {runs_with_reads} with at least one read. {reads_total} reads, "
            f"{weighed_total} with a weight. Muse Spark 1.3 over {len(spark)} timed reads: median "
            f"{statistics.median(spark) / 1000:.1f} s, 90th percentile "
            f"{spark[int(len(spark) * 0.9)] / 1000:.1f} s."
        ),
        "",
    ]
    (HERE / "recorded-runs.org").write_text("\n".join(out))
    print(out[-2])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
